COMPS = [("xyzw"), ("rgba")]

def swizzles(n):
    res = []
    for names in COMPS:
        letters = names[:n]
        for k in range(1, 5):
            for combo in itertools.product(range(n), repeat=k):
                name = "".join(letters[i] for i in combo)
                ext = "".join("xyzw"[i] for i in combo)
                res.append((name, ext, k, len(set(combo)) == k))
    return res

