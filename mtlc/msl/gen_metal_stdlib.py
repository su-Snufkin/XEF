# per element-type intrinsic names: resolve the _T__ placeholder through a type-dispatch helper
# (members call __xef_X_<cls>_T__(...): expand to an overload set keyed on T)
import re
def expand(text):
    # find all used placeholder function names
    names = set(re.findall(r"(__xef_\w+?)_T__\(", text))
    helpers = []
    for base in sorted(names):
        # collect existing per-type variants: base_<type>
        variants = re.findall(r'extern "C" [^;]*? ' + re.escape(base) + r'_(float|half|int|uint|short|ushort)\(', text)
        variants = sorted(set(variants))
        if not variants:
            continue
        helpers.append(f"template <class T> struct {base}_sel;")
        for v in variants:
            helpers.append(f"template <> struct {base}_sel<{v}> {{ template <class... A> static XEF_INL auto call(A... a) {{ return {base}_{v}(a...); }} }};")
    text = re.sub(r"(__xef_\w+?)_T__\(", r"\1_sel<T>::call(", text)
    # insert helpers before the first texture class template
    marker = "template <class T, access A = access::sample, memory_coherence __MC = memory_coherence_threadgroup> struct texture1d {"
    i = text.index(marker)
    return text[:i] + "\n".join(helpers) + "\n" + text[i:]

