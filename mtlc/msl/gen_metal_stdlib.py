"""Generates mtlc/msl/include/metal_stdlib: the Metal Shading Language standard library for xef-mtlc's MSL frontend.

MSL is compiled as C++20 (aarch64 target) after a light rewrite done by frontend.cpp. Address space qualifiers are
erased (device/thread -> nothing, constant -> const); the compiler recovers memory kinds from pointer provenance.
Vectors are classes over clang ext_vector storage with __declspec(property) swizzles; GPU operations call AIR
intrinsics (asm labels) understood by the xef-mtlc SPIR-V emitter, math lowers to LLVM intrinsics."""
